import { Router } from 'express'; import { prisma } from '../config/database.js';
export const apiRouter = Router();
apiRouter.post('/auth/login', (_req,res)=>res.json({token:'demo-jwt'}));
apiRouter.get('/auth/me', (_req,res)=>res.json({name:'AJ'}));
apiRouter.get('/products', async (_q,r)=>r.json(await prisma.product.findMany()));
apiRouter.post('/products', async (q,r)=>r.json(await prisma.product.create({data:q.body})));
apiRouter.patch('/products/:id', async (q,r)=>r.json(await prisma.product.update({where:{id:q.params.id},data:q.body})));
apiRouter.delete('/products/:id', async (q,r)=>r.json(await prisma.product.delete({where:{id:q.params.id}})));
apiRouter.get('/categories', async (_q,r)=>r.json(await prisma.category.findMany()));
apiRouter.post('/categories', async (q,r)=>r.json(await prisma.category.create({data:q.body})));
apiRouter.get('/orders', async (_q,r)=>r.json(await prisma.order.findMany()));
apiRouter.patch('/orders/:id/status', async (q,r)=>r.json(await prisma.order.update({where:{id:q.params.id},data:{status:q.body.status}})));
apiRouter.get('/customers', async (_q,r)=>r.json(await prisma.customer.findMany()));
apiRouter.get('/media', async (_q,r)=>r.json(await prisma.mediaFile.findMany()));
apiRouter.get('/broadcasts', async (_q,r)=>r.json(await prisma.broadcast.findMany()));
apiRouter.post('/broadcasts', async (q,r)=>r.json(await prisma.broadcast.create({data:q.body})));
apiRouter.get('/settings', async (_q,r)=>r.json(await prisma.botSetting.findMany()));
apiRouter.patch('/settings', async (q,r)=>r.json(await prisma.botSetting.upsert({where:{key:q.body.key},update:{value:q.body.value},create:{key:q.body.key,value:q.body.value}})));
apiRouter.get('/analytics/summary', async (_q,r)=>r.json({orders: await prisma.order.count(), products: await prisma.product.count(), customers: await prisma.customer.count()}));
